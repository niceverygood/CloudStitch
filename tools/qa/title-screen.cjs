const fs = require('node:fs');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {repoPath,reportDirectory,launchBrowser}=require('../lib/runtime.cjs');
const reportDir=reportDirectory('title-screen',process.argv[3]);
const input=repoPath(process.argv[2] || 'outputs/cloudstitch-title-screen/index.html');
(async () => {
  const browser = await launchBrowser();
  const page = await browser.newPage({viewport:{width:1600,height:900},deviceScaleFactor:1});
  const errors=[], external=[]; page.on('pageerror', error => errors.push(error.message)); page.on('request',request => {if (/^https?:/.test(request.url())) external.push(request.url());});
  await page.goto(pathToFileURL(input).href);
  await page.locator('.sky img').evaluate(image => image.decode());
  await page.locator('.brand img').evaluate(image => image.decode());
  await page.waitForTimeout(1200);
  await page.screenshot({path:path.join(reportDir,'qa-desktop.png')});
  const disabled = await page.locator('.menu-button').nth(1).isDisabled();
  await page.getByRole('button',{name:'새로운 항해',exact:true}).click();
  const prologue = await page.locator('#prologue').evaluate(dialog => dialog.open);
  await page.screenshot({path:path.join(reportDir,'qa-prologue.png')});
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'설정',exact:true}).click();
  const before = await page.locator('#motion-switch').getAttribute('aria-checked');
  await page.locator('#motion-switch').click();
  const after = await page.locator('#motion-switch').getAttribute('aria-checked');
  const motionDisabled = await page.evaluate(()=>document.body.classList.contains('still'));
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'새로운 항해',exact:true}).focus();
  await page.keyboard.press('ArrowDown');
  const keyboardSkipsDisabled = await page.evaluate(()=>document.activeElement.textContent==='설정');
  await page.getByRole('button',{name:'만든 사람들',exact:true}).click();
  const credits = await page.locator('#credits').evaluate(dialog=>dialog.open);
  await page.keyboard.press('Escape');
  let fullscreen = 'unsupported';
  if (!(await page.locator('#fullscreen').isDisabled())) {
    await page.locator('#fullscreen').click();
    await page.waitForTimeout(150);
    fullscreen = await page.evaluate(()=>!!document.fullscreenElement);
    if(fullscreen) await page.evaluate(()=>document.exitFullscreen());
  }
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(reportDir,'qa-mobile.png')});
  const mobileOverflow = await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth);
  await page.getByRole('button',{name:'새로운 항해',exact:true}).click();
  const mobilePrologueFits = await page.locator('#prologue').evaluate(dialog=>dialog.getBoundingClientRect().width <= innerWidth && dialog.getBoundingClientRect().height <= innerHeight);
  const reducedContext=await browser.newContext({reducedMotion:'reduce'});
  const reducedPage=await reducedContext.newPage();
  await reducedPage.goto(pathToFileURL(input).href);
  const reducedDefault=await reducedPage.evaluate(()=>document.body.classList.contains('still')&&getComputedStyle(document.querySelector('.sky img')).animationName==='none');
  await reducedPage.getByRole('button',{name:'설정',exact:true}).click();
  await reducedPage.locator('#motion-switch').click();
  const reducedOptIn=await reducedPage.evaluate(()=>!document.body.classList.contains('still')&&getComputedStyle(document.querySelector('.sky img')).animationName==='drift');
  const result={errors,external,disabled,prologue,credits,motionToggle:before!==after,motionDisabled,keyboardSkipsDisabled,fullscreen,mobileOverflow,mobilePrologueFits,reducedDefault,reducedOptIn};
  result.passed=errors.length===0&&external.length===0&&disabled&&prologue&&credits&&result.motionToggle&&motionDisabled&&keyboardSkipsDisabled&&!mobileOverflow&&mobilePrologueFits&&reducedDefault&&reducedOptIn;
  fs.writeFileSync(path.join(reportDir,'qa-result.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2)); await browser.close(); if(!result.passed) process.exitCode=1;
})().catch(error=>{console.error(error);process.exit(1)});
